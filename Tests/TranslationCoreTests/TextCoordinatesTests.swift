import Foundation
import Testing
@testable import TranslationCore

@Test func chromiumParagraphCaretFindsMarkerInDisplayedLine() throws {
    let text = "前の行。\nこんにちは...\n後の行。"
    let indexed = text.replacingOccurrences(of: "\n", with: "")
    let coordinates = try TextCoordinates(displayed: text, indexed: indexed)
    let nativeReplacement = (indexed as NSString).range(of: "こんにちは...")
    let caret = NSRange(location: NSMaxRange(nativeReplacement), length: 0)
    let targets = try coordinates.displayedRanges(for: caret).compactMap {
        try? TextTarget(text: text, selection: $0, mode: .triggeredLine(.dots))
    }
    #expect(targets.count == 1)
    let target = try #require(targets.first)
    #expect(target.sourceText == "こんにちは")
    #expect(try coordinates.indexedRange(for: target.replacementRange) == nativeReplacement)
    #expect(target.replacing(with: "Hello") == "前の行。\nHello\n後の行。")
}

@Test func coordinateMappingPreservesEmojiAndExplicitLineBreaks() throws {
    let text = "🙂 前\n日本語...\n後"
    let identity = try TextCoordinates(displayed: text, indexed: text)
    let range = (text as NSString).range(of: "日本語...")
    #expect(identity.isIdentity)
    #expect(try identity.indexedRange(for: range) == range)
    #expect(try identity.displayedRanges(for: range) == [range])
    let indexed = text.replacingOccurrences(of: "\n", with: "")
    let mapped = try TextCoordinates(displayed: text, indexed: indexed)
    #expect(try mapped.indexedRange(for: range) == (indexed as NSString).range(of: "日本語..."))
}

@Test func generatedBlankLinesDoNotGuessWhichLineOwnsCaret() throws {
    let mapping = try TextCoordinates(displayed: "A\n\nB", indexed: "AB")
    #expect(try mapping.displayedRanges(for: NSRange(location: 1, length: 0)) == [
        NSRange(location: 1, length: 0), NSRange(location: 2, length: 0), NSRange(location: 3, length: 0)
    ])
}

@Test func unrelatedIndexedTextIsRejectedInsteadOfCorrected() {
    #expect(throws: InputError.unsupported) { try TextCoordinates(displayed: "A\nB", indexed: "AXB") }
    #expect(throws: InputError.unsupported) { try TextCoordinates(displayed: "A B", indexed: "AB") }
    #expect(throws: InputError.unsupported) { try TextCoordinates(displayed: "AB", indexed: "ABC") }
}

@Test func coordinateRangesOutsideTextAreRejected() throws {
    let mapping = try TextCoordinates(displayed: "A\nB", indexed: "AB")
    #expect(throws: InputError.invalidRange) { try mapping.indexedRange(for: NSRange(location: 3, length: 1)) }
    #expect(throws: InputError.invalidRange) { try mapping.displayedRanges(for: NSRange(location: 3, length: 0)) }
    #expect(throws: InputError.invalidRange) { try mapping.indexedRange(for: NSRange(location: -1, length: 0)) }
}

@Test func multilineSelectionAcceptsOnlyVerifiedParagraphSeparatorDifferences() throws {
    // First LF is generated by the editor; the second is a real indexed LF.
    let displayed = "🙂前\n日本語\n後:::"
    let indexed = "🙂前日本語\n後:::"
    let mapping = try TextCoordinates(displayed: displayed, indexed: indexed)
    let whole = NSRange(location: 0, length: displayed.utf16.count)
    #expect(try mapping.matchesSelectedText(displayed, range: whole))
    #expect(try mapping.matchesSelectedText(indexed, range: whole))
    #expect(try !mapping.matchesSelectedText("🙂前日本語後:::", range: whole))
    #expect(try !mapping.matchesSelectedText("🙂前別の本文\n後:::", range: whole))
    let partial = (displayed as NSString).range(of: "前\n日本語")
    #expect(try mapping.matchesSelectedText("前日本語", range: partial))
    #expect(try !mapping.matchesSelectedText(indexed, range: partial))
}

@Test func selectionOfExplicitNewlinesMustKeepThem() throws {
    let text = "前\n後:::"
    let mapping = try TextCoordinates(displayed: text, indexed: text)
    let whole = NSRange(location: 0, length: text.utf16.count)
    #expect(try !mapping.matchesSelectedText("前後:::", range: whole))
}

@Test func pastedParagraphsAllowDoubleLFOnlyAtVerifiedGeneratedSeparators() throws {
    let displayed = "🙂First\nSecond\nThird"
    let mapping = try TextCoordinates(displayed: displayed, indexed: "🙂FirstSecondThird")
    #expect(mapping.matchesPastedText(displayed))
    #expect(mapping.matchesPastedText("🙂First\n\nSecond\n\nThird"))
    #expect(!mapping.matchesPastedText("🙂FirstSecond\nThird"))
    #expect(!mapping.matchesPastedText("🙂First\n\n\nSecond\nThird"))
    #expect(!mapping.matchesPastedText("🙂First\nSecond!\nThird"))
    #expect(!mapping.matchesPastedText("🙂First\n Second\nThird"))
    #expect(!mapping.matchesPastedText("🙂First\nSecond\nThird\n"))

    let mixed = try TextCoordinates(displayed: displayed, indexed: "🙂FirstSecond\nThird")
    #expect(mixed.matchesPastedText("🙂First\n\nSecond\nThird"))
    #expect(!mixed.matchesPastedText("🙂First\nSecond\n\nThird"))
    let plain = try TextCoordinates(displayed: displayed, indexed: displayed)
    #expect(!plain.matchesPastedText("🙂First\n\nSecond\nThird"))
}

@Test func paragraphEvidenceSurvivesChangedRangeRepresentationAfterPaste() throws {
    let original = try TextCoordinates(displayed: "前\n中\n後:::", indexed: "前中後:::")
    let current = "First\nMiddle\nLast"
    // Observed in Arc/Bluesky: range reads include LF after paste, even though
    // the same field's range reads omitted them before paste.
    let after = try TextCoordinates(displayed: current, indexed: current)
    let expected = "First\n\nMiddle\n\nLast"
    #expect(!after.matchesPastedText(expected))
    #expect(after.matchesPastedText(expected, original: original))
    #expect(!after.matchesPastedText("First\n\nChanged\n\nLast", original: original))
    #expect(!after.matchesPastedText("First\n\nMiddle \n\nLast", original: original))
    #expect(!after.matchesPastedText("FirstMiddle\n\nLast", original: original))
    #expect(!after.matchesPastedText(expected + "\n", original: original))
    let plainOriginal = try TextCoordinates(displayed: "前\n中\n後:::", indexed: "前\n中\n後:::")
    #expect(!after.matchesPastedText(expected, original: plainOriginal))
}
